use std::fs;
use std::path::PathBuf;

use carbide_proto_compiler::{CompilerConfig, TonicBuilderCodegenExt, compile};
use tonic_client_wrapper::codegen;

const PROTO_FILES: &[&str] = &[
    "proto/codegen/v1/machine_id_types.proto",
    "proto/common.proto",
    "proto/scout_firmware_upgrade.proto",
    "proto/forge.proto",
    "proto/machine_discovery.proto",
    "proto/mlx_device.proto",
    "proto/nmx_c.proto",
    "proto/site_explorer.proto",
    "proto/dns.proto",
    "proto/fmds.proto",
];
const INCLUDE_PATHS: &[&str] = &["proto"];

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("cargo:rerun-if-changed=proto");
    println!("cargo:rerun-if-changed=../agent/proto");

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
    // Write generated code to OUT_DIR rather than back into the source tree.
    // Consumers pull these in via:
    // `include!(concat!(env!("OUT_DIR"), "/X.rs"))` in `src/protos/mod.rs`
    let autogenerated_rust_output_directory = out_dir.clone();
    // The reflection path is part of the output directory (which might be debug or release),
    // so that different builds get a different binary file and concurrent builds don't collide
    let reflection = out_dir.join("forge.bin");

    // AgentLocal is the dpu-agent's local unix-socket service (issue #355).
    // The agent owns the file and serves it; this crate provides the client
    // for `SocketTokenSource` and the server bindings the agent uses. Keeping
    // both sides here ensures there is one generated Rust representation.
    //
    // Compiled outside the schema below on purpose: that schema feeds the API's
    // reflection descriptor, and nico-api does not serve AgentLocal.
    tonic_prost_build::configure()
        .build_server(true)
        .build_client(true)
        .compile_protos(&["../agent/proto/agent_local.proto"], &["../agent/proto"])?;

    // Run protoc once as the schema frontend. The resulting Schema fans out to
    // every code-generation backend and to runtime reflection.
    let schema = compile(&CompilerConfig {
        proto_files: PROTO_FILES.iter().map(PathBuf::from).collect(),
        include_paths: INCLUDE_PATHS.iter().map(PathBuf::from).collect(),
        protoc_args: Vec::new(),
    })?;

    // Preserve protoc's exact bytes for reflection, including any custom
    // annotation values. No sanitization or prost_types re-encoding occurs.
    fs::write(&reflection, &schema.raw_descriptor_set)?;

    let codegen = schema.collect_codegen()?;
    let rust_descriptor_set = codegen.rust_file_descriptor_set(&schema.file_descriptor_set)?;

    let derive_prost_builder =
        "#[cfg_attr(feature = \"test-support\", derive(carbide_prost_builder::Builder))]";

    let prost_builder = tonic_prost_build::configure()
        .apply_codegen(&codegen)
        .type_attribute(
            ".google.protobuf.Timestamp",
            "#[derive(serde::Serialize, serde::Deserialize)]",
        )
        .type_attribute(
            ".forge.DeletedFilter",
            "#[cfg_attr(feature = \"cli\", derive(clap::ValueEnum))]",
        )
        .type_attribute(
            ".forge.DpuMode",
            "#[cfg_attr(feature = \"cli\", derive(clap::ValueEnum))]",
        )
        .type_attribute(
            ".forge.DpaInterfaceType",
            "#[cfg_attr(feature = \"cli\", derive(clap::ValueEnum))]",
        )
        .type_attribute(
            ".forge.BmcIpAllocationType",
            "#[cfg_attr(feature = \"cli\", derive(clap::ValueEnum))]",
        )
        .include_file("prost_common.rs")
        .type_attribute(".health", "#[derive(serde::Deserialize, serde::Serialize)]")
        .type_attribute(
            ".machine_discovery",
            "#[derive(serde::Deserialize, serde::Serialize)]",
        )
        .type_attribute(
            ".site_explorer",
            "#[derive(serde::Deserialize, serde::Serialize)]",
        )
        .type_attribute(
            ".mlx_device",
            "#[derive(serde::Deserialize, serde::Serialize)]",
        )
        .type_attribute(".dns", "#[derive(serde::Serialize)]")
        .type_attribute("forge.DhcpDiscovery", derive_prost_builder)
        .field_attribute(
            "ExpectedHostNic.role",
            "#[serde(default, skip_serializing_if = \"Option::is_none\", deserialize_with = \"ExpectedInterfaceRole::deserialize_optional\", serialize_with = \"ExpectedInterfaceRole::serialize_optional\")]",
        )
        .field_attribute(
            "ExpectedHostNic.ip_allocation",
            "#[serde(default, skip_serializing_if = \"Option::is_none\", deserialize_with = \"ExpectedInterfaceIpAllocation::deserialize_optional\", serialize_with = \"ExpectedInterfaceIpAllocation::serialize_optional\")]",
        )
        // `ExpectedMachine` is serialize-only here. If it gains `Deserialize`,
        // this rename also needs `alias = "host_nics"` for older payloads.
        .field_attribute(
            "ExpectedMachine.host_nics",
            "#[serde(rename = \"interfaces\")]",
        )
        .field_attribute(
            "ExpectedMachine.replace_host_nics",
            "#[serde(skip_serializing)]",
        )
        .field_attribute(
            "forge.NetworkSecurityGroupRuleAttributes.direction",
            "#[serde(deserialize_with = \"NetworkSecurityGroupRuleDirection::from_string\", serialize_with = \"NetworkSecurityGroupRuleDirection::serialize_from_enum_i32\")]",
        )
        .field_attribute(
            "forge.NetworkSecurityGroupRuleAttributes.protocol",
            "#[serde(deserialize_with = \"NetworkSecurityGroupRuleProtocol::from_string\", serialize_with = \"NetworkSecurityGroupRuleProtocol::serialize_from_enum_i32\")]",
        )
        .field_attribute(
            "forge.NetworkSecurityGroupRuleAttributes.action",
            "#[serde(deserialize_with = \"NetworkSecurityGroupRuleAction::from_string\", serialize_with = \"NetworkSecurityGroupRuleAction::serialize_from_enum_i32\")]",
        )
        .type_attribute(
            "forge.NetworkSecurityGroupRuleAttributes.source_net",
            "#[serde(rename_all=\"snake_case\")]",
        )
        .type_attribute(
            "forge.NetworkSecurityGroupRuleAttributes.destination_net",
            "#[serde(rename_all=\"snake_case\")]",
        )
        .field_attribute("Sku.schema_version", "#[serde(default)]")
        .field_attribute("Sku.associated_machine_ids", "#[serde(default)]")
        .field_attribute("SkuComponentStorage.vendor", "#[serde(default)]")
        .field_attribute("SkuComponentStorage.capacity_mb", "#[serde(default)]")
        .field_attribute("SkuComponentStorage.min_size_mb", "#[serde(default)]")
        .field_attribute("SkuComponentStorage.max_size_mb", "#[serde(default)]")
        .field_attribute("SkuComponentStorage.pci_patterns", "#[serde(default)]")
        .field_attribute("machine_discovery.BlockDevice.device_type", "#[serde(default)]")
        .field_attribute("machine_discovery.NvmeDevice.serial", "#[serde(default)]")
        .field_attribute(
            "forge.InstanceTypeMachineCapabilityFilterAttributes.capability_type",
            "#[serde(deserialize_with = \"MachineCapabilityType::from_string\", serialize_with = \"MachineCapabilityType::serialize_from_enum_i32\")]",
        )
        .field_attribute(
            "forge.InstanceTypeMachineCapabilityFilterAttributes.device_type",
            "#[serde(deserialize_with = \"MachineCapabilityDeviceType::from_string\", serialize_with = \"MachineCapabilityDeviceType::serialize_from_enum_i32\")]",
        )
        .field_attribute(
            "machine_discovery.DiscoveryInfo.memory_device_groups",
            "#[serde(default, skip_serializing_if = \"Vec::is_empty\")]",
        )

        .type_attribute(
            ".rack_manager",
            "#[derive(serde::Deserialize, serde::Serialize)]",
        )
        .type_attribute(
            ".nmx_c",
            "#[derive(serde::Deserialize, serde::Serialize)]",
        )
        .type_attribute(
            "common.MachineId",
            "#[derive(Ord, PartialOrd)]",
        )
        .type_attribute(
            "common.PowerShelfId",
            "#[derive(Ord, PartialOrd)]",
        )
        .type_attribute(
            "common.SwitchId",
            "#[derive(Ord, PartialOrd)]",
        )
        .type_attribute("forge.VpcCreationRequest", derive_prost_builder)
        .type_attribute("forge.VpcUpdateRequest", derive_prost_builder)
        .type_attribute("forge.VpcDeletionRequest", derive_prost_builder)
        .type_attribute("forge.InstanceAllocationRequest", derive_prost_builder)
        .type_attribute("forge.InstanceConfigUpdateRequest", derive_prost_builder)
        .type_attribute("forge.InstanceConfig", derive_prost_builder)
        .type_attribute("forge.ComputeAllocationAttributes", derive_prost_builder)
        .type_attribute("forge.CreateComputeAllocationRequest", derive_prost_builder)
        .type_attribute("forge.UpdateComputeAllocationRequest", derive_prost_builder)
        .type_attribute("forge.DeleteComputeAllocationRequest", derive_prost_builder)
        .type_attribute(
            ".forge.NetworkSegmentType",
            "#[cfg_attr(feature = \"cli\", derive(clap::ValueEnum))]",
        )
        .type_attribute(
            ".forge.VpcVirtualizationType",
            "#[cfg_attr(feature = \"cli\", derive(clap::ValueEnum))]",
        )
        .build_server(true)
        .build_client(true)
        .out_dir(autogenerated_rust_output_directory);

    // Wrapper backends borrow the complete decoded descriptor set so request
    // and response types imported from any file can be resolved. `root_files`
    // only selects the services for which each backend generates methods.
    let client_wrapper_config = codegen::Config {
        wrapper_name: "ForgeApiClient".to_string(),
        inner_rpc_client_type: "crate::forge_tls_client::ForgeClientT".to_string(),
        root_files: vec!["forge.proto".to_string()],
        generated_types_path_within_crate: "protos".to_string(),
        extern_paths: codegen.extern_paths(),
    };
    let client_wrapper_generator =
        codegen::CodeGenerator::new(client_wrapper_config, &rust_descriptor_set)?;

    client_wrapper_generator.write_rpc_client_wrapper(out_dir.join("forge_api_client.rs"))?;
    client_wrapper_generator
        .write_rpc_convenience_converters(out_dir.join("convenience_converters.rs"))?;

    // Generate the NMX-C wrapper from the same descriptor set.
    let nmx_c_client_wrapper_config = codegen::Config {
        wrapper_name: "NmxCApiClient".to_string(),
        inner_rpc_client_type: "crate::forge_tls_client::NmxCClientT".to_string(),
        root_files: vec!["nmx_c.proto".to_string()],
        extern_paths: Default::default(),
        generated_types_path_within_crate: "protos".to_string(),
    };
    let nmx_c_client_wrapper =
        codegen::CodeGenerator::new(nmx_c_client_wrapper_config, &rust_descriptor_set)?;
    nmx_c_client_wrapper.write_rpc_client_wrapper(out_dir.join("nmx_c_client.rs"))?;
    nmx_c_client_wrapper.write_rpc_convenience_converters(out_dir.join("nmx_c_converters.rs"))?;

    // Both wrapper generators are done borrowing the descriptor set. Transfer
    // ownership to tonic/prost last; compile_fds renders Rust without invoking
    // protoc again.
    prost_builder.compile_fds(rust_descriptor_set)?;

    Ok(())
}
