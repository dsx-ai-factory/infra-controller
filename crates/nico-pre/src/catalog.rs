//! The check catalogue: every registered check of every checklist, indexed by
//! id, with its expected condition, whether it is implemented, and its spec
//! (what it reads, when it passes, warns, fails or skips, and how it is tested).
//! `nico-pre checks` prints it; `CHECKS.md` is its Markdown form, regenerated
//! with `nico-pre checks --format md` and kept current by a test.

use std::fmt::Write as _;

use crate::checklists::Checklist;

/// One line per check: id, implemented or todo, expected.
pub(crate) fn text() -> String {
    let mut out = String::new();
    let (total, done) = totals();
    let _ = writeln!(out, "{total} checks, {done} implemented");
    for cl in Checklist::ALL {
        let _ = writeln!(out);
        let _ = writeln!(out, "{}", cl.name());
        let width = cl.checks().iter().map(|c| c.id.len()).max().unwrap_or(0);
        for c in cl.checks() {
            let mark = if c.implemented() { "✓" } else { "·" };
            let _ = writeln!(out, "  {mark} {:<width$}  {}", c.id, c.expected);
        }
    }
    out
}

/// The catalogue as Markdown, one section per checklist and one heading per
/// check so an issue or a result can link to it; GitHub drops the dots from the
/// heading's anchor, so `fabric.bgp.sessions` is linked as `CHECKS.md#fabricbgpsessions`.
pub(crate) fn markdown() -> String {
    let mut out = String::new();
    let (total, done) = totals();
    out.push_str("# nico-pre checks\n\n");
    out.push_str(
        "Generated by `nico-pre checks --format md` from the checklist tables under \
         `src/checklists/`. Do not edit; change the table entry and regenerate with\n\n\
         ```bash\ncargo run -q -p nico-pre -- checks --format md > crates/nico-pre/CHECKS.md\n```\n\n",
    );
    let _ = writeln!(
        out,
        "{total} checks, {done} implemented. A check that is registered but not written yet \
         prints as a ⚠ row until it lands."
    );
    for cl in Checklist::ALL {
        let checks = cl.checks();
        let done = checks.iter().filter(|c| c.implemented()).count();
        let _ = writeln!(out);
        let _ = writeln!(
            out,
            "## {} ({done} of {} implemented)",
            cl.name(),
            checks.len()
        );
        for c in checks {
            let _ = writeln!(out);
            let _ = writeln!(out, "### {}", c.id);
            let _ = writeln!(out);
            let status = if c.implemented() {
                "implemented"
            } else {
                "not implemented yet"
            };
            let _ = writeln!(out, "- Status: {status}");
            let _ = writeln!(out, "- Expected: {}", c.expected);
            for line in c.detail.lines() {
                let _ = writeln!(out, "- {line}");
            }
        }
    }
    out
}

fn totals() -> (usize, usize) {
    let all = Checklist::ALL.iter().flat_map(|cl| cl.checks());
    let total = all.clone().count();
    let done = all.filter(|c| c.implemented()).count();
    (total, done)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// CHECKS.md is what `nico-pre checks --format md` prints today.
    #[test]
    fn checks_md_is_current() {
        let committed = include_str!("../CHECKS.md");
        assert!(
            committed == markdown(),
            "CHECKS.md is stale; regenerate with \
             `cargo run -q -p nico-pre -- checks --format md > crates/nico-pre/CHECKS.md`"
        );
    }

    #[test]
    fn text_lists_every_check_once() {
        let t = text();
        for cl in Checklist::ALL {
            for c in cl.checks() {
                assert_eq!(t.matches(c.id).count(), 1, "{} in the text catalogue", c.id);
            }
        }
    }
}
