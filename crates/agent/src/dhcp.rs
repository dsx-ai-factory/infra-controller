use std::net::{Ipv4Addr, Ipv6Addr};

use ::rpc::forge as rpc;
use carbide_rpc_utils::dhcp::HostConfig;
use gtmpl_derive::Gtmpl;

use crate::HBNDeviceNames;

/// The path we write in non-NVUE mode, when using dhcp-relay (versus dhcp-server)
pub(super) const RELAY_PATH: &str = "etc/supervisor/conf.d/default-isc-dhcp-relay.conf";

/// The path NVUE writes if we're using dhcp-relay
pub(super) const RELAY_PATH_NVUE: &str = "etc/supervisor/conf.d/isc-dhcp-relay-default";

pub(super) const SERVER_PATH: &str = "etc/supervisor/conf.d/default-forge-dhcp-server.conf";
pub(super) const SERVER_CONFIG_PATH: &str = "var/support/forge-dhcp/conf/dhcp.yaml";
pub(super) const SERVER_HOST_CONFIG_PATH: &str = "var/support/forge-dhcp/conf/host.yaml";

pub(super) const TMPL_EMPTY: &str = "# Auto-generated by Forge!";
const TMPL_SERVER: &str = include_str!("../templates/default-forge-dhcp-server.conf");

pub(super) const RELOAD_CMD: &str = "supervisorctl update";
// Since we don't update default-forge-dhcp-server.conf file, supervisord does not restart it on
// `supervisorctl update` command.
pub(super) const RELOAD_DHCP_SERVER: &str =
    "supervisorctl update;supervisorctl restart forge-dhcp-server-default";

pub(super) const STOP_DHCP_SERVER: &str =
    "supervisorctl update;supervisorctl stop forge-dhcp-server-default";

/// Preferred lifetime advertised for DPU-side DHCPv6 address bindings.
pub(super) const DHCPV6_PREFERRED_LIFETIME_SECS: u32 = 3600;
/// Valid lifetime advertised for DPU-side DHCPv6 address bindings.
pub(super) const DHCPV6_VALID_LIFETIME_SECS: u32 = 7200;

/// Generate default-forge-dhcp-server.conf
pub(super) fn build_server_supervisord_config(
    conf: DhcpServerSupervisordConfig,
) -> Result<String, eyre::Report> {
    let params = TmplDHCServerConfigParameters {
        Interfaces: conf.interfaces,
        Autostart: conf.autostart,
    };
    gtmpl::template(TMPL_SERVER, params).map_err(|e| e.into())
}

/// An empty default-isc-dhcp-relay.conf
pub(super) fn blank() -> String {
    gtmpl::template(TMPL_EMPTY, "").expect("dhcp blank template cannot fail")
}

pub(super) fn build_server_config(
    pxe_ip: Ipv4Addr,
    ntpservers: Vec<Ipv4Addr>,
    ntpservers_v6: Vec<Ipv6Addr>,
    nameservers: Vec<Ipv4Addr>,
    nameservers_v6: Vec<Ipv6Addr>,
    loopback_ip: Ipv4Addr,
) -> Result<String, eyre::Report> {
    let mut dhcp_config = carbide_rpc_utils::dhcp::DhcpConfig::from_forge_dhcp_config(
        pxe_ip,
        ntpservers,
        nameservers,
        nameservers_v6,
        loopback_ip,
    )?;

    // The legacy constructor owns common/v4 fields; apply the new v6-only
    // option source and explicit nonzero address lifetimes here.
    dhcp_config.carbide_ntpservers_v6 = ntpservers_v6;
    dhcp_config.dhcpv6_preferred_lifetime_secs = DHCPV6_PREFERRED_LIFETIME_SECS;
    dhcp_config.dhcpv6_valid_lifetime_secs = DHCPV6_VALID_LIFETIME_SECS;

    Ok(serde_yaml::to_string(&dhcp_config)?)
}

pub(super) fn build_server_host_config(
    conf: rpc::ManagedHostNetworkConfigResponse,
    hbn_devic_names: &HBNDeviceNames,
) -> Result<String, eyre::Report> {
    Ok(serde_yaml::to_string(&HostConfig::try_from(
        conf,
        hbn_devic_names.reps[0],
        hbn_devic_names.virt_rep_begin,
        hbn_devic_names.sf_id,
        true,
    )?)?)
}

pub(super) struct DhcpServerSupervisordConfig {
    pub(super) interfaces: Vec<String>,
    pub(super) autostart: bool,
}

//
// Go template object, hence allow(non_snake_case)
//

#[allow(non_snake_case)]
#[derive(Clone, Gtmpl)]
struct TmplDHCRelayConfigParameters {
    Uplinks: Vec<String>,
    VlanIDs: Vec<u32>,
    Servers: Vec<String>,
    RemoteId: String,
}

#[allow(non_snake_case)]
#[derive(Clone, Gtmpl)]
struct TmplDHCServerConfigParameters {
    Interfaces: Vec<String>,
    Autostart: bool,
}
